"""
Automated Firmware Flasher for Standalone ESP32 + Tapo + Firebase Rig
Predictive Maintenance (PdM) SideProject

Flashes 06_standalone_tapo_streamer.ino.merged.bin to ESP32 via USB (COM3) or OTA.
Can automatically recompile using the bundled Arduino CLI if requested.

Usage:
  py -3.12 firmware/06_standalone_tapo_streamer/flash_firmware.py [--port COM3] [--compile]
"""

import sys
import time
import os
import subprocess
import argparse
import serial.tools.list_ports
from pathlib import Path

PYTHON_EXE = sys.executable
FIRMWARE_DIR = Path(__file__).resolve().parent
PROJECT_DIR = FIRMWARE_DIR.parent.parent
BUILD_DIR = FIRMWARE_DIR / "build"
TARGET_BIN = BUILD_DIR / "06_standalone_tapo_streamer.ino.merged.bin"
SECRETS_H = FIRMWARE_DIR / "secrets.h"
ENV_FILE = PROJECT_DIR / ".env"

DEFAULT_ARDUINO_CLI = Path(
    r"C:\Users\adamd\AppData\Local\Programs\Arduino IDE\resources\app\lib\backend\resources\arduino-cli.exe"
)

def get_args():
    parser = argparse.ArgumentParser(description="Flash Standalone ESP32 Firmware")
    parser.add_argument("--port", type=str, default="COM3", help="Serial port (default: COM3)")
    parser.add_argument("--baud", type=str, default="921600", help="Baud rate (default: 921600)")
    parser.add_argument("--compile", action="store_true", help="Recompile sketch before flashing")
    return parser.parse_args()

def sync_secrets_from_env():
    """Generates secrets.h from .env if .env exists."""
    if not ENV_FILE.is_file():
        return
    env_vars = {}
    for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            env_vars[k.strip()] = v.strip().strip('"').strip("'")
            
    wifi_ssid = env_vars.get("WIFI_SSID", "leo")
    wifi_pass = env_vars.get("WIFI_PASS", "jj67680205")
    fb_host = env_vars.get("FIREBASE_HOST", "https://pdm-anomaly-detection-default-rtdb.asia-southeast1.firebasedatabase.app")
    fb_auth = env_vars.get("FIREBASE_AUTH", "18mHDNCCisVdpFjUHbPnOASYWbZylX1QQ5sCx61V")
    tapo_ip = env_vars.get("TAPO_IP", "192.168.0.45")
    tapo_user = env_vars.get("TAPO_DEVICE_USER", "admin")
    tapo_pass = env_vars.get("TAPO_DEVICE_PASS", "pdm123456")

    secrets_code = f"""// Auto-generated by flash_firmware.py from .env
#ifndef SECRETS_H
#define SECRETS_H

const char* WIFI_SSID     = "{wifi_ssid}";
const char* WIFI_PASS     = "{wifi_pass}";
const char* FIREBASE_HOST = "{fb_host}";
const char* FIREBASE_AUTH = "{fb_auth}";

const char* TAPO_IP       = "{tapo_ip}";
const char* TAPO_USER     = "{tapo_user}";
const char* TAPO_PASS     = "{tapo_pass}";

#endif // SECRETS_H
"""
    SECRETS_H.write_text(secrets_code, encoding="utf-8")
    print("[CONFIG] Synchronized secrets.h with .env settings.")

def compile_sketch():
    cli_exe = None
    if DEFAULT_ARDUINO_CLI.is_file():
        cli_exe = str(DEFAULT_ARDUINO_CLI)
    else:
        # Search PATH
        import shutil
        found = shutil.which("arduino-cli")
        if found:
            cli_exe = found

    if not cli_exe:
        print("[ERROR] arduino-cli not found. Cannot recompile sketch.")
        return False

    print("\n" + "=" * 65)
    print("   COMPILING FIRMWARE VIA ARDUINO-CLI (MIN_SPIFFS 1.9MB APP)    ")
    print("=" * 65)
    sync_secrets_from_env()

    cmd = [
        cli_exe, "compile",
        "--fqbn", "esp32:esp32:esp32:PartitionScheme=min_spiffs",
        "--build-path", str(BUILD_DIR),
        str(FIRMWARE_DIR)
    ]
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, check=True)
        print(res.stdout)
        print("[SUCCESS] Compilation green! Merged binary created.")
        return True
    except subprocess.CalledProcessError as e:
        print(f"[COMPILATION ERROR]\n{e.stderr or e.stdout}")
        return False

def kill_serial_monitors():
    try:
        subprocess.run(
            ["powershell", "-Command", "Stop-Process -Name 'serial-monitor' -Force -ErrorAction SilentlyContinue"],
            capture_output=True
        )
    except Exception:
        pass

def flash(port: str, baud: str, should_compile: bool = False, max_loops: int = 15):
    if should_compile or not TARGET_BIN.is_file():
        success = compile_sketch()
        if not success:
            return False

    print("=" * 65)
    print("   FLASHING STANDALONE ESP32 + TAPO FIRMWARE (ZERO PC NEEDED)   ")
    print("=" * 65)
    print(f"Target Binary : {TARGET_BIN}")
    print(f"Target Port   : {port}")
    print(f"Baud Rate     : {baud}")
    print("=" * 65)

    if not TARGET_BIN.is_file():
        print(f"[ERROR] Binary not found at: {TARGET_BIN}")
        return False

    kill_serial_monitors()
    time.sleep(0.5)

    print("\n[PROBING] Searching for ESP32 on USB...")
    print("Tip: If it does not connect, PRESS AND HOLD the 'BOOT' button on the ESP32.\n")

    for attempt in range(1, max_loops + 1):
        kill_serial_monitors()
        ports = [p.device for p in serial.tools.list_ports.comports()]
        if port not in ports:
            print(f"[{time.strftime('%H:%M:%S')}] Waiting for {port} to be connected via USB ({attempt}/{max_loops})...")
            time.sleep(1.5)
            continue

        current_baud = baud if attempt % 2 != 0 else "115200"
        print(f"[{time.strftime('%H:%M:%S')}] Attempting flash on {port} at {current_baud} baud...")

        cmd = [
            PYTHON_EXE, "-m", "esptool",
            "--port", port,
            "--chip", "esp32",
            "--baud", current_baud,
            "--before", "default-reset",
            "--after", "hard-reset",
            "--connect-attempts", "5",
            "write-flash",
            "--flash-mode", "dio",
            "--flash-freq", "80m",
            "--flash-size", "4MB",
            "0x0",
            str(TARGET_BIN)
        ]

        try:
            p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
            connected = False
            for line in iter(p.stdout.readline, ''):
                sys.stdout.write(line)
                sys.stdout.flush()
                if "Chip is ESP32" in line or "Uploading stub..." in line:
                    if not connected:
                        connected = True
                        print("\n>>> [CONNECTED] Uploading standalone firmware...\n")
            p.wait()
            if p.returncode == 0:
                print("\n" + "=" * 65)
                print("[SUCCESS] Standalone ESP32 firmware successfully flashed 100%!")
                print("Your ESP32 will now autonomously poll Tapo P110 and stream to Firebase.")
                print("=" * 65)
                return True
        except Exception as e:
            print(f"[ERROR] Flash attempt failed: {e}")

        time.sleep(1)

    print(f"\n[FAILED] Could not connect to {port} after {max_loops} attempts.")
    return False

if __name__ == "__main__":
    args = get_args()
    flash(args.port, args.baud, should_compile=args.compile)
