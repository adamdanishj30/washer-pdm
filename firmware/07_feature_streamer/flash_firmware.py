"""
flash_firmware.py - compile and flash firmware 07 (windowed feature streamer)
Predictive Maintenance (PdM) SideProject

What it does
  1. Generates secrets.h from the project .env (WIFI_SSID, WIFI_PASS,
     FIREBASE_HOST, FIREBASE_AUTH, TAPO_IP, TAPO_DEVICE_USER, TAPO_DEVICE_PASS,
     optional OTA_PASS). There are NO built-in fallback credentials: a missing
     key stops the build with a clear message.
  2. Compiles with arduino-cli (esp32:esp32, min_spiffs partition).
  3. Flashes over USB with esptool.

Usage
  py -3.12 firmware/07_feature_streamer/flash_firmware.py --compile --port COM3
  py -3.12 firmware/07_feature_streamer/flash_firmware.py --compile-only
"""

# =============================================================================
# SECTION 1: Imports & paths
# =============================================================================
import argparse
import shutil
import subprocess
import sys
import time
from pathlib import Path

FIRMWARE_DIR = Path(__file__).resolve().parent
PROJECT_DIR = FIRMWARE_DIR.parent.parent
BUILD_DIR = FIRMWARE_DIR / "build"
SKETCH_NAME = FIRMWARE_DIR.name                       # 07_feature_streamer
TARGET_BIN = BUILD_DIR / f"{SKETCH_NAME}.ino.merged.bin"
SECRETS_H = FIRMWARE_DIR / "secrets.h"
ENV_FILE = PROJECT_DIR / ".env"
FQBN = "esp32:esp32:esp32:PartitionScheme=min_spiffs"

# Same default location as the 06 flasher (Arduino IDE 2 bundled CLI)
DEFAULT_ARDUINO_CLI = Path.home() / "AppData/Local/Programs/Arduino IDE/resources/app/lib/backend/resources/arduino-cli.exe"

REQUIRED_KEYS = ["WIFI_SSID", "WIFI_PASS", "FIREBASE_HOST", "FIREBASE_AUTH"]
TAPO_KEYS = ["TAPO_IP", "TAPO_DEVICE_USER", "TAPO_DEVICE_PASS"]


# =============================================================================
# SECTION 2: .env -> secrets.h
# =============================================================================
def read_env(path: Path) -> dict:
    """Minimal .env parser (KEY=VALUE, # comments, optional quotes)."""
    env = {}
    if not path.is_file():
        return env
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip().strip('"').strip("'")
    return env


def c_escape(value: str) -> str:
    """Escape a value for a C string literal."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def write_secrets(use_tapo: bool) -> None:
    env = read_env(ENV_FILE)
    needed = REQUIRED_KEYS + (TAPO_KEYS if use_tapo else [])
    missing = [k for k in needed if not env.get(k)]
    if missing:
        sys.exit(f"[ERROR] {ENV_FILE} is missing: {', '.join(missing)} (no fallback credentials by design)")
    host = env["FIREBASE_HOST"].rstrip("/")
    lines = [
        "// Auto-generated by flash_firmware.py from .env - do not share or commit",
        "#ifndef SECRETS_H", "#define SECRETS_H",
        f'const char* WIFI_SSID     = "{c_escape(env["WIFI_SSID"])}";',
        f'const char* WIFI_PASS     = "{c_escape(env["WIFI_PASS"])}";',
        f'const char* FIREBASE_HOST = "{c_escape(host)}";',
        f'const char* FIREBASE_AUTH = "{c_escape(env["FIREBASE_AUTH"])}";',
        f'const char* TAPO_IP       = "{c_escape(env.get("TAPO_IP", ""))}";',
        f'const char* TAPO_USER     = "{c_escape(env.get("TAPO_DEVICE_USER", ""))}";',
        f'const char* TAPO_PASS     = "{c_escape(env.get("TAPO_DEVICE_PASS", ""))}";',
    ]
    if env.get("OTA_PASS"):
        lines.append(f'#define OTA_PASS "{c_escape(env["OTA_PASS"])}"')
    else:
        print("[WARN] OTA_PASS not set in .env: anyone on your Wi-Fi could reflash the rig over OTA.")
    lines.append("#endif")
    SECRETS_H.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[CONFIG] secrets.h generated from .env ({'with' if use_tapo else 'without'} Tapo)")


# =============================================================================
# SECTION 3: Compile
# =============================================================================
def find_cli() -> str:
    if DEFAULT_ARDUINO_CLI.is_file():
        return str(DEFAULT_ARDUINO_CLI)
    found = shutil.which("arduino-cli")
    if not found:
        sys.exit("[ERROR] arduino-cli not found (install Arduino IDE 2 or put arduino-cli on PATH)")
    return found


def compile_sketch(use_tapo: bool) -> None:
    write_secrets(use_tapo)
    cmd = [find_cli(), "compile", "--fqbn", FQBN, "--build-path", str(BUILD_DIR),
           "--build-property", f"compiler.cpp.extra_flags=-DUSE_TAPO={1 if use_tapo else 0}",
           "--warnings", "default", str(FIRMWARE_DIR)]
    print("[BUILD]", " ".join(cmd))
    res = subprocess.run(cmd, text=True)
    if res.returncode != 0:
        sys.exit("[ERROR] compilation failed (see output above)")
    print("[BUILD] OK ->", TARGET_BIN)


# =============================================================================
# SECTION 4: Flash
# =============================================================================
def flash(port: str, baud: str) -> None:
    if not TARGET_BIN.is_file():
        sys.exit(f"[ERROR] {TARGET_BIN} not found - run with --compile first")
    cmd = [sys.executable, "-m", "esptool", "--chip", "esp32", "--port", port, "--baud", baud,
           "--before", "default-reset", "--after", "hard-reset", "write-flash",
           "--flash-mode", "dio", "--flash-freq", "80m", "--flash-size", "4MB", "0x0", str(TARGET_BIN)]
    for attempt in range(1, 4):
        print(f"[FLASH] attempt {attempt}: {port} @ {baud} (hold BOOT if it does not connect)")
        if subprocess.run(cmd).returncode == 0:
            print("[FLASH] done. Open http://washer-pdm.local/ to check the rig.")
            return
        time.sleep(1.5)
        baud = "115200"
    sys.exit("[ERROR] flashing failed")


def main() -> None:
    ap = argparse.ArgumentParser(description="Compile/flash firmware 07")
    ap.add_argument("--port", default="COM3")
    ap.add_argument("--baud", default="921600")
    ap.add_argument("--compile", action="store_true", help="compile before flashing")
    ap.add_argument("--compile-only", action="store_true", help="compile and stop")
    ap.add_argument("--no-tapo", action="store_true", help="build without the on-device Tapo client")
    a = ap.parse_args()
    if a.compile or a.compile_only:
        compile_sketch(use_tapo=not a.no_tapo)
    if not a.compile_only:
        flash(a.port, a.baud)


if __name__ == "__main__":
    main()
